"use strict";
// Deliberately no bundler/dependencies: wrap the exact, unmodified upstream source.
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { createHash } = require('node:crypto');
const source = readFileSync(join(__dirname, '../parcel-event-audit/index.js'), 'utf8');
const sha = createHash('sha256').update(source).digest('hex');
const bundle = '// Generated by build.cjs; upstream SHA-256: ' + sha + '\n' +
  'const module = { exports: {} };\n' +
  'function require(name) {\n' +
  '  if (name === "node:util") return { TextDecoder: globalThis.TextDecoder };\n' +
  '  if (name === "node:fs") return { constants: {} };\n' +
  '  if (name === "node:fs/promises") return { open() { throw new Error("Filesystem access is unavailable in the browser"); } };\n' +
  '  throw new Error("Unsupported dependency: " + name);\n' +
  '}\n(function(module, require) {\n' + source + '\n})(module, require);\n' +
  'export const { auditExports, InputError } = module.exports;\n';
const target = join(__dirname, 'audit.browser.mjs');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== bundle) throw new Error('Browser audit bundle differs; run node parcel-exception-review/build.cjs');
  console.log('Browser bundle matches the unchanged upstream source: ' + sha);
} else {
  writeFileSync(target, bundle);
  console.log('Built browser audit wrapper: ' + sha);
}
