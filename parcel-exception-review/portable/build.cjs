"use strict";
// This is a packaging adapter, not another reconciliation implementation.
// All original files are read-only. Only ../review.html is generated.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { Script } = require('node:vm');
const root = path.resolve(__dirname, '..');
const sha = text => createHash('sha256').update(text).digest('hex');
const cspHash = text => "'sha256-" + createHash('sha256').update(text).digest('base64') + "'";
function replaceOnce(text, before, after, name) {
  if (text.split(before).length !== 2) throw new Error('Source contract changed: ' + name);
  return text.replace(before, () => after);
}
function buildPortable() {
  const inputs = ['../parcel-event-audit/index.js', 'audit.browser.mjs', 'review.mjs', 'app.mjs', 'index.html', 'styles.css', 'example.json', 'portable/help.html'];
  const sources = Object.fromEntries(inputs.map(name => [name, fs.readFileSync(path.resolve(root, name), 'utf8')]));
  const upstream = sources['../parcel-event-audit/index.js'];
  let audit = sources['audit.browser.mjs'];
  if (!audit.startsWith('// Generated by build.cjs; upstream SHA-256: ' + sha(upstream) + '\n') ||
      !audit.includes('(function(module, require) {\n' + upstream + '\n})(module, require);')) {
    throw new Error('Browser wrapper does not contain the exact current upstream source. Check the modular build first.');
  }
  audit = replaceOnce(audit, 'export const { auditExports, InputError } = module.exports;', 'const { auditExports, InputError } = module.exports;', 'audit exports');
  let adapter = replaceOnce(sources['review.mjs'], "import { auditExports, InputError } from './audit.browser.mjs';", '', 'adapter import');
  adapter = adapter.replace(/^export (?=const |function )/gm, '');
  let app = replaceOnce(sources['app.mjs'], "import { reviewBytes, matchingIndices, issueEvents, issueParcels, issueLabel, exportSelection, MAX_BYTES } from './review.mjs';", '', 'application import');
  const fetchExample = "  const response = await fetch('./example.json');\n  if (!response.ok) throw new Error('The local synthetic example could not be read. Choose a file instead.');\n  return new File([await response.arrayBuffer()], 'synthetic-example.json', { type: 'application/json' });";
  app = replaceOnce(app, fetchExample, "  return new File([PORTABLE_EXAMPLE_TEXT], 'synthetic-example.json', { type: 'application/json' });", 'embedded example');
  if (/^\s*(?:import|export)\s/m.test(audit + adapter + app)) throw new Error('Unconverted module syntax');
  if (/\b(?:fetch|XMLHttpRequest|WebSocket)\s*\(/.test(audit + adapter + app)) throw new Error('Unexpected network API in portable application');
  const example = JSON.stringify(sources['example.json']).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  const script = '\n"use strict";\n(() => {\ntry {\n' +
    'if (typeof TextDecoder !== "function" || typeof TextEncoder !== "function" || typeof File !== "function" || typeof File.prototype.arrayBuffer !== "function" || typeof String.prototype.isWellFormed !== "function") throw new Error("Use a current browser with UTF-8 and File API support.");\n' +
    'const PORTABLE_EXAMPLE_TEXT = ' + example + ';\n' + audit + '\n' + adapter + '\n' + app + '\n' +
    'document.getElementById("download-example").addEventListener("click", () => download(PORTABLE_EXAMPLE_TEXT, "synthetic-events.json", "application/json"));\n' +
    'document.querySelectorAll("[data-portable-enable]").forEach(control => { control.disabled = false; });\n' +
    'document.getElementById("portable-startup").hidden = true;\n' +
    'document.getElementById("portable-ready").textContent = "Portable engine ready · all assets embedded · no network access";\n' +
    'document.documentElement.dataset.portableReady = "true";\n' +
    '} catch (error) {\n' +
    '  const warning = document.getElementById("portable-startup"); warning.hidden = false;\n' +
    '  warning.textContent = "Review engine could not start: " + (error.message || "unknown initialization error") + ". No file has been reviewed. Save review.html and open it in a current browser.";\n' +
    '  document.getElementById("review").hidden = true;\n' +
    '  document.querySelectorAll("input, button, select").forEach(control => { control.disabled = true; });\n' +
    '}\n})();\n';
  new Script(script, { filename: 'portable-inline.js' });
  if (/<\/script/i.test(script)) throw new Error('Unsafe inline script delimiter');
  const css = '\n' + sources['styles.css'] + '\n';
  if (/<\/style/i.test(css)) throw new Error('Unsafe inline style delimiter');
  let html = sources['index.html'];
  const policy = "default-src 'none'; script-src " + cspHash(script) + "; style-src " + cspHash(css) + "; img-src data:; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'";
  html = html.replace(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/, '<meta http-equiv="Content-Security-Policy" content="' + policy + '">');
  html = replaceOnce(html, '<link rel="stylesheet" href="styles.css">', '<style>' + css + '</style>', 'embedded styles');
  html = replaceOnce(html, '  <script type="module" src="app.mjs"></script>', '', 'remove module loader');
  html = replaceOnce(html, '<title>Parcel exception review · Dispatch</title>', '<title>Parcel exception review · Portable offline edition</title>', 'portable title');
  html = replaceOnce(html, 'class="brand" href="./"', 'class="brand" href="#top"', 'local brand link');
  html = replaceOnce(html, '<body>', '<body id="top">', 'document anchor');
  html = replaceOnce(html, '● Local browser review', '● Portable · Offline', 'portable badge');
  html = replaceOnce(html, '<a href="example.json" download="synthetic-events.json">Download example</a>', '<button id="download-example" type="button" class="quiet">Download example</button>', 'embedded example download');
  html = replaceOnce(html, '<a href="README.md" target="_blank" rel="noopener">Usage &amp; input format ↗</a>', '<a href="#portable-help">Usage &amp; input format ↓</a>', 'embedded usage link');
  const notice = '<div id="portable-startup" class="error" role="alert"><strong>Review engine has not started.</strong> If this warning stays visible, scripts are blocked or unsupported in this preview. No file has been reviewed; file selection is disabled. Save review.html and open it directly in a current browser.</div>\n<p id="portable-ready" class="small muted" role="status">Portable startup pending</p>\n<p class="small muted">Single-file edition. Previews must allow scripts and downloads. If a download does not appear, open the saved review.html directly in your browser.</p>\n';
  html = replaceOnce(html, '<section class="import-panel"', notice + '<section class="import-panel"', 'visible startup guard');
  html = replaceOnce(html, '    <footer>', sources['portable/help.html'] + '\n    <footer>', 'embedded help');
  // Safe before startup: a non-executing preview cannot silently accept a file.
  html = html.replace(/<(input|button|select)\b[^>]*>/g, tag => /\bdisabled(?:[\s=>])/.test(tag) ? tag : tag.slice(0, -1) + ' disabled data-portable-enable>');
  html = replaceOnce(html, '</body>', '<script>' + script + '</script>\n</body>', 'embedded classic script');
  const manifest = Object.entries(sources).map(([name, source]) => name + ': ' + sha(source)).join('\n');
  html = replaceOnce(html, '<!doctype html>', '<!doctype html>\n<!-- Generated by portable/build.cjs; no timestamps, paths, partner inputs or proof data.\n' + manifest + '\n-->','reproducible manifest');
  if (/<(?:script|link)\b[^>]*(?:src|href)="(?!data:)/i.test(html)) throw new Error('Unexpected external resource');
  return html;
}
module.exports = { buildPortable };
if (require.main === module) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node parcel-exception-review/portable/build.cjs [--check]');
  const output = buildPortable();
  const target = path.join(root, 'review.html');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Portable artifact differs; rebuild with node parcel-exception-review/portable/build.cjs');
    console.log('Portable build is byte-for-byte reproducible: ' + sha(output));
  } else {
    fs.writeFileSync(target, output);
    console.log('Built standalone review.html (' + Buffer.byteLength(output) + ' bytes); SHA-256 ' + sha(output));
  }
}
